// Helper lưu trữ và lấy dữ liệu Master Data từ localStorage để hỗ trợ thêm món mới
const STORAGE_KEY = "FOODPRINT_DISH_CATALOG";

export function getStoredDishCatalog() {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) return parsed;
    }
  } catch (err) {
    console.warn("Lỗi đọc dish catalog từ storage:", err);
  }
  return INITIAL_DISH_CATALOG;
}

export function saveDishToCatalog(newDish) {
  const current = getStoredDishCatalog();
  const created = {
    ...newDish,
    id: newDish.id || `dish-cat-custom-${Date.now()}`,
    portionQty: Number(newDish.portionQty) || 50,
    unit: newDish.unit || "g",
  };
  const updated = [created, ...current];
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(updated));
  } catch (err) {
    console.warn("Lỗi lưu dish catalog vào storage:", err);
  }
  return updated;
}

