// Helper lưu trữ và lấy dữ liệu Master Data từ localStorage
const STORAGE_KEY = "FOODPRINT_DISH_CATALOG_V2";

export function getStoredDishCatalog() {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed.map((dish) => {
          // Chuẩn hóa nhóm cũ sang nhóm mới nếu có
          let cat = dish.category;
          let catLabel = dish.categoryLabel;
          if (cat === "AFTERNOON") {
            cat = dish.name.toLowerCase().includes("súp") ? "MAIN_DISH" : "DESSERT";
            catLabel = cat === "MAIN_DISH" ? "Món mặn" : "Món tráng miệng";
          } else if (cat === "ALLERGY_SUBSTITUTE") {
            cat = dish.name.toLowerCase().includes("sữa") ? "DESSERT" : "MAIN_DISH";
            catLabel = cat === "DESSERT" ? "Món tráng miệng" : "Món mặn";
          }
          const initial = INITIAL_DISH_CATALOG.find((d) => d.id === dish.id || d.name === dish.name);
          return {
            ...dish,
            category: cat,
            categoryLabel: catLabel,
            unit: dish.unit === "ml" ? "ml" : "g",
            mainIngredient: dish.mainIngredient || initial?.mainIngredient || dish.ingredientNames?.[0] || dish.name,
            supplierId: dish.supplierId || initial?.supplierId || "sup-cp",
            supplierName: dish.supplierName || initial?.supplierName || "CP Foods Việt Nam",
            supplierBadge: dish.supplierBadge || initial?.supplierBadge || "VietGAP",
          };
        });
      }
    }
  } catch (err) {
    console.warn("Lỗi đọc dish catalog từ storage:", err);
  }
  return INITIAL_DISH_CATALOG;
}

export function saveDishToCatalog(newDish) {
  const current = getStoredDishCatalog();
  const catObj = DISH_CATEGORIES.find((c) => c.key === newDish.category);
  const created = {
    ...newDish,
    id: newDish.id || `dish-cat-custom-${Date.now()}`,
    categoryLabel: catObj ? catObj.label : "Món ăn",
    portionQty: Number(newDish.portionQty) || 50,
    unit: newDish.unit === "ml" ? "ml" : "g",
    mainIngredient: newDish.mainIngredient || newDish.name,
    supplierName: newDish.supplierName || "CP Foods Việt Nam",
    supplierBadge: newDish.supplierBadge || "VietGAP",
  };
  const updated = [created, ...current];
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(updated));
  } catch (err) {
    console.warn("Lỗi lưu dish catalog vào storage:", err);
  }
  return updated;
}
